export interface StarSentence {
  prefix: string;
  suffix: string;
  blocks: string[]; // 4 scrambled word blocks
  starSlotIndex: number; // 0..3 index of the block that belongs in the ★ slot
  correctSentence: string;
}

const SECRET_SALT = "JLPT_N5_SECURE_EXAM_SALT_2026";

export function encryptAnswer(questionId: number, answerIndex: number): string {
  const str = `${questionId}:${SECRET_SALT}:${answerIndex}`;
  const base64 = typeof btoa === "function" ? btoa(str) : Buffer.from(str).toString("base64");
  return base64.split("").reverse().join("");
}

export function verifyAnswer(questionId: number, selectedIndex: number, encryptedAnswer: string): boolean {
  if (selectedIndex === undefined || selectedIndex === null) return false;
  return encryptAnswer(questionId, selectedIndex) === encryptedAnswer;
}

